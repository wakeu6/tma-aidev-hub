/**
 * Валидатор темы на соответствие таймлайну 2026 года и стоп-листу аналитики.
 */
export function validateTrend2026(trend, dynamicStopList = []) {
  const fullText = `${trend.topic} ${trend.hook} ${trend.segments.map(s => s.text).join(' ')}`.toLowerCase();
  
  for (const forbidden of [...DEPRECATED_MODELS_STOPLIST, ...dynamicStopList]) {
    if (fullText.includes(forbidden.toLowerCase())) {
      return {
        valid: false,
        reason: `Тема содержит устаревшую или заблокированную модель: "${forbidden}"`,
      };
    }
  }

  // Проверка структуры: 5 сцен (Сцена 1: Hook, Сцены 2-4: Body, Сцена 5: Outro CTA)
  if (trend.segments.length !== 5) {
    return { valid: false, reason: 'Сценарий должен состоять строго из 5 смысловых сегментов' };
  }

  return { valid: true };
}

